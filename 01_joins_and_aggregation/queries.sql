/*
----------------------------------------------------------
Q06 - Gross Sales Detail

Business Question:
What is the gross sales value generated by each
customer-product-date combination?

Gross Sales =
sold_quantity × gross_price_per_item

SQL Concepts:
- Multiple INNER JOINs
- Fact + Dimension analysis
- Calculated columns
- ROUND()
----------------------------------------------------------
*/

SELECT
    s.date,
    s.fiscal_year,
    s.customer_code,
    c.customer,
    c.market,
    s.product_code,
    p.product,
    p.variant,
    s.sold_quantity,
    g.gross_price AS gross_price_per_item,
    ROUND(
        s.sold_quantity * g.gross_price,
        2
    ) AS gross_price_total
FROM fact_sales_monthly AS s
JOIN dim_product AS p
    ON s.product_code = p.product_code
JOIN dim_customer AS c
    ON s.customer_code = c.customer_code
JOIN fact_gross_price AS g
    ON g.fiscal_year = s.fiscal_year
    AND g.product_code = s.product_code;


/*
----------------------------------------------------------
Q07 - Gross Sales by Market

Business Question:
What is the gross sales value generated by each market?

SQL Concepts:
- Multiple JOINs
- Aggregation
- Calculated measures
----------------------------------------------------------
*/

SELECT
    c.market,
    ROUND(
        SUM(s.sold_quantity * g.gross_price),
        2
    ) AS gross_sales
FROM fact_sales_monthly AS s
JOIN dim_customer AS c
    ON s.customer_code = c.customer_code
JOIN fact_gross_price AS g
    ON g.fiscal_year = s.fiscal_year
    AND g.product_code = s.product_code
GROUP BY c.market
ORDER BY gross_sales DESC;



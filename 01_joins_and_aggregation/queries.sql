/*
----------------------------------------------------------
Q09 - Pre-Invoice Discount Detail

Business Question:
How can sales, product, gross price, and pre-invoice
deduction data be combined into a detailed sales report?

SQL Concepts:
- Multiple fact/dimension joins
- Join using fiscal year
- Calculated gross sales
----------------------------------------------------------
*/

SELECT
    s.date,
    s.product_code,
    p.product,
    p.variant,
    s.sold_quantity,
    g.gross_price AS gross_price_per_item,
    ROUND(
        s.sold_quantity * g.gross_price,
        2
    ) AS gross_price_total,
    pre.pre_invoice_discount_pct
FROM fact_sales_monthly AS s
JOIN dim_product AS p
    ON s.product_code = p.product_code
JOIN fact_gross_price AS g
    ON g.fiscal_year = get_fiscal_year(s.date)
    AND g.product_code = s.product_code
JOIN fact_pre_invoice_deductions AS pre
    ON pre.customer_code = s.customer_code
    AND pre.fiscal_year = get_fiscal_year(s.date);


/*
----------------------------------------------------------
Q10 - Top Markets by Gross Sales Within Each Region

Business Question:
What are the highest gross-sales markets within each
region for a selected fiscal year?

SQL Concepts:
- JOIN
- GROUP BY
- CTE
- Aggregation
- Regional business analysis

Note:
The ranking version of this analysis is placed in
05_advanced_analytical_sql.
----------------------------------------------------------
*/

SELECT
    c.region,
    c.market,
    ROUND(
        SUM(gs.gross_price_total) / 1000000,
        2
    ) AS gross_sales_mln
FROM gross_sales AS gs
JOIN dim_customer AS c
    ON c.customer_code = gs.customer_code
WHERE gs.fiscal_year = 2021
GROUP BY
    c.region,
    c.market
ORDER BY
    c.region,
    gross_sales_mln DESC;
